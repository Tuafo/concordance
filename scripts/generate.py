"""Streaming text generation with lossless speculative drafting from Concordance LiveMemory.

During generation, the counted index acts as a zero-parameter draft model:
  - Drafts up to K bytes by following the longest matching suffix's most recent continuation.
  - Verifies all K+1 positions in ONE forward pass of the reader.
  - Greedy mode (temp == 0): bit-identical to plain greedy decoding.
  - Sampling mode (temp > 0): exact speculative sampling with a deterministic draft (identical distribution).

You can swap or stack indexes via `--index dir1 dir2 ...` to adapt a frozen reader to any corpus instantly.

Example:
    python scripts/generate.py checkpoints/concordance_g4k.pt --index data/live --len 300 --k 8
"""

from __future__ import annotations

import argparse
import os
import sys
import time

import numpy as np
import torch

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from concordance.live import LiveMemory
from concordance.model import Hybrid


def draft_next_byte(feat: np.ndarray) -> int | None:
    """Longest matching suffix order's most recent continuation (None if no order matches)."""
    has = feat[:, 1] > 0
    if not has.any():
        return None
    return int(feat[np.nonzero(has)[0][-1], 0])


def run_generate(
    model: Hybrid,
    prompt_bytes: list[int],
    mem: LiveMemory | None,
    length: int = 300,
    temp: float = 0.8,
    k_draft: int = 8,
    seed: int = 0,
    device: str = "cpu",
    stream_memory: bool = True,
) -> tuple[list[int], float, float]:
    """Generate `length` bytes and return (generated_bytes, bytes_per_pass, ms_per_byte)."""
    ctx = model.ctx
    use_mem = bool(model.corpus_orders) and mem is not None
    text: list[int] = []
    feats: list[np.ndarray] = []

    if use_mem:
        mem.reset()
        for b in prompt_bytes:
            mem.append(b)
            text.append(b)
            feats.append(mem.features(stream=stream_memory))
    else:
        text.extend(prompt_bytes)

    def push(b: int) -> None:
        text.append(b)
        if use_mem:
            mem.append(b)
            feats.append(mem.features(stream=stream_memory))

    def pop() -> None:
        text.pop()
        if use_mem:
            mem.pop()
            feats.pop()

    def tail_logits(m: int) -> torch.Tensor:
        x = torch.tensor(text[-ctx:], dtype=torch.long, device=device)[None]
        cf = torch.from_numpy(np.stack(feats[-ctx:])).to(device)[None] if use_mem else None
        with torch.no_grad():
            return (model(x, cf) if cf is not None else model(x))[0, -m:].float().cpu()

    g = torch.Generator().manual_seed(seed)
    n0 = len(text)
    passes = 0
    t0 = time.time()

    while len(text) - n0 < length:
        draft: list[int] = []
        if use_mem and k_draft > 0:
            max_d = min(k_draft, length - (len(text) - n0) - 1)
            while len(draft) < max_d:
                d = draft_next_byte(feats[-1])
                if d is None:
                    break
                draft.append(d)
                push(d)

        lg = tail_logits(len(draft) + 1)
        passes += 1

        accepted = 0
        next_byte: int | None = None
        for i, d in enumerate(draft):
            if temp == 0.0:
                pred = int(lg[i].argmax())
                if pred == d:
                    accepted += 1
                    continue
                next_byte = pred
            else:
                p = torch.softmax(lg[i] / temp, -1)
                if torch.rand((), generator=g).item() < float(p[d]):
                    accepted += 1
                    continue
                p[d] = 0.0
                next_byte = int(torch.multinomial(p / p.sum(), 1, generator=g))
            break

        for _ in range(len(draft) - accepted):
            pop()

        if next_byte is None:
            i = len(draft)
            if temp == 0.0:
                next_byte = int(lg[i].argmax())
            else:
                next_byte = int(torch.multinomial(torch.softmax(lg[i] / temp, -1), 1, generator=g))
        push(next_byte)

    elapsed_ms = 1000.0 * (time.time() - t0) / max(1, length)
    return text[n0 : n0 + length], length / max(1, passes), elapsed_ms


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate bytes with Concordance + lossless LiveMemory speculative decoding.")
    ap.add_argument("ckpt", help="Path to trained Hybrid checkpoint (.pt)")
    ap.add_argument("--index", nargs="*", default=["data/live"], help="One or more LiveMemory index directories")
    ap.add_argument("--no-index", action="store_true", help="Do not load a disk index (stream prompt/output only)")
    ap.add_argument("--frozen-memory", action="store_true", help="Do not stream generated bytes into LiveMemory")
    ap.add_argument("--prompt-text", default="", help="UTF-8 prompt text (overrides --data/--offset)")
    ap.add_argument("--data", default="data/enwik8")
    ap.add_argument("--offset", type=int, default=92_000_000, help="Byte offset into --data when --prompt-text is omitted")
    ap.add_argument("--prompt-bytes", type=int, default=600)
    ap.add_argument("--len", type=int, default=300)
    ap.add_argument("--temp", type=float, default=0.8)
    ap.add_argument("--k", type=int, default=8, help="Speculative draft horizon (0 disables speculation)")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    ap.add_argument("--verify-greedy", action="store_true", help="Assert greedy speculative output equals plain greedy")
    args = ap.parse_args()

    ck = torch.load(args.ckpt, map_location="cpu", weights_only=False)
    if ck.get("model") != "hybrid":
        raise ValueError(f"Expected a 'hybrid' checkpoint, got model={ck.get('model')!r}")
    model = Hybrid(**ck["cfg"]).to(args.device)
    model.load_state_dict(ck["state"])
    model.eval()

    mem = None
    if model.corpus_orders:
        mem = LiveMemory(None if args.no_index else args.index)

    if args.prompt_text:
        prompt = list(args.prompt_text.encode("utf-8"))
    else:
        raw = np.fromfile(args.data, dtype=np.uint8, count=args.offset + args.prompt_bytes + 5000)
        s = args.offset
        nl = bytes(raw[s : s + 5000]).find(b"\n")
        if nl >= 0:
            s += nl + 1
        prompt = [int(b) for b in raw[s : s + args.prompt_bytes]]

    out, bpp, ms = run_generate(
        model=model,
        prompt_bytes=prompt,
        mem=mem,
        length=args.len,
        temp=args.temp,
        k_draft=args.k,
        seed=args.seed,
        device=args.device,
        stream_memory=not args.frozen_memory,
    )
    print(f"[{bpp:.2f} bytes/pass, {ms:.1f} ms/byte, temp={args.temp}, k={args.k}]")
    print(bytes(out).decode("utf-8", errors="replace"))

    if args.verify_greedy:
        ref, _, _ = run_generate(
            model=model,
            prompt_bytes=prompt,
            mem=mem,
            length=args.len,
            temp=0.0,
            k_draft=0,
            seed=args.seed,
            device=args.device,
            stream_memory=not args.frozen_memory,
        )
        spec, spec_bpp, _ = run_generate(
            model=model,
            prompt_bytes=prompt,
            mem=mem,
            length=args.len,
            temp=0.0,
            k_draft=max(1, args.k),
            seed=args.seed,
            device=args.device,
            stream_memory=not args.frozen_memory,
        )
        assert ref == spec, "Greedy speculative output diverged from plain greedy decoding!"
        print(f"[verify-greedy OK: bit-identical output at {spec_bpp:.2f} bytes/pass]")


if __name__ == "__main__":
    main()
